#!/usr/bin/env bash
# Guard: the set of crates linked into the `mdview` binary.
#
# Compares `cargo tree -e normal` (names + versions, sorted, unique) with the
# committed snapshot tests/guards/runtime-deps.txt. Any added, removed or
# upgraded crate fails until it's blessed, so a dependency change is always a
# deliberate, reviewed step (docs/contributing.md: "No new dependencies
# without a measured reason").
#
# Only normal edges are followed: build-dependencies (cc, pkg-config, ...) run
# at compile time and never reach the binary, so they don't affect startup or
# binary size, and bumps to them would only add noise. Proc-macros are normal
# edges, so they are included. The target is pinned to x86_64 Linux so the
# snapshot doesn't depend on the host.
#
# Usage: scripts/guards/runtime-deps.sh [--bless]
set -euo pipefail
# shellcheck source=../lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib.sh"
cd "$MDVIEW_ROOT"

SNAPSHOT=tests/guards/runtime-deps.txt
TARGET=x86_64-unknown-linux-gnu

generate() {
    {
        echo "# Crates linked into the mdview binary (cargo tree -e normal, $TARGET)."
        echo "# Generated by scripts/guards/runtime-deps.sh. Don't edit by hand: after an"
        echo "# intentional dependency change, run scripts/check.sh --bless and put the"
        echo "# measured startup/size impact in the commit message (scripts/startup-bench.sh)."
        cargo tree --locked --quiet --color never -p mdview -e normal --target "$TARGET" \
            --prefix none --format '{p}' |
            sed -E 's/ \(\*\)$//; s/ \([^)]*\)$//' | LC_ALL=C sort -u
    }
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
generate >"$tmp"

if [[ ${1:-} == --bless ]]; then
    if ! diff -q "$SNAPSHOT" "$tmp" >/dev/null 2>&1; then
        diff -u --label committed --label now "$SNAPSHOT" "$tmp" 2>/dev/null | grep -E '^[+-][^+-]' || true
        cp "$tmp" "$SNAPSHOT"
        ok "blessed $SNAPSHOT"
    else
        ok "$SNAPSHOT is up to date"
    fi
    exit 0
fi

compare_snapshot "$SNAPSHOT" "$tmp" "The runtime dependencies ($SNAPSHOT)" "scripts/check.sh --bless" \
    "  New or changed crates cost build time, binary size and often startup time.
  Rule: no new dependencies without measured numbers (docs/contributing.md#performance-rules).
  Measure with scripts/startup-bench.sh --ref origin/main and put the output in the commit message."
ok "runtime dependencies match $SNAPSHOT ($(grep -vc '^#' "$SNAPSHOT") crates)"
